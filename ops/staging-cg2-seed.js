#!/usr/bin/env node
'use strict';
// =====================================================
// IDauto — IDA-CG2 STAGING seed (ops/staging-cg2.sh init / reset run it)
// ops/staging-cg2-seed.js
//
// Fills a FRESH staging database with:
//   - two workshops (organisations): « Atelier Démo Staging » and « Autre Atelier Staging »;
//   - four web accounts: admin, workshop manager, workshop technician, manager of the
//     OTHER workshop (to prove isolation) — random passwords written to the 0600 accounts
//     file named by IDAUTO_STAGING_ACCOUNTS, never printed;
//   - the vehicles the acceptance scenarios need (docs/STAGING_CG2.md §5): one existing
//     vehicle, and two vehicles whose plate and VIN conflict.
// Every value is SYNTHETIC (« SPÉCIMEN »): no real plate, VIN, person or workshop.
// Refuses to run unless the database is the staging one (idauto_scratch_cg2_*) and
// IDAUTO_STAGING=1 — never against production.
// =====================================================

var fs = require('fs');
var path = require('path');
var crypto = require('crypto');

// The synthetic cards (ops/staging-cg2-samples.js draws them from the same list).
var FIXTURES = {
  // Card A — a vehicle IDauto does not know: « create » (step 9), then the same card again (step 10).
  A: { plate_series: 101, plate_number: 2001, vin: 'VF3STGA0000000101', make: 'PEUGEOT', model: '208', date: '12/03/2019', fuel: 'ESSENCE', cc: 1199, seats: 5, fiscal: 6 },
  // Card B — the vehicle already in IDauto (seeded below with plate + VIN): « link » (step 11).
  B: { plate_series: 102, plate_number: 2002, vin: 'VF1STGB0000000102', make: 'RENAULT', model: 'CLIO', date: '05/07/2017', fuel: 'DIESEL', cc: 1461, seats: 5, fiscal: 5 },
  // Card C — plate of vehicle F, VIN of vehicle G: ambiguous (steps 12 and 14).
  C: { plate_series: 103, plate_number: 2003, vin: 'WVWSTGC0000000103', make: 'VOLKSWAGEN', model: 'POLO', date: '20/01/2016', fuel: 'ESSENCE', cc: 1390, seats: 5, fiscal: 7 }
};
// Holder lines printed on every card so the test proves they are dropped (D5) — fictitious.
var HOLDER = { name: 'SPECIMEN FICTIF', address: '1 RUE DU TEST, VILLE FICTIVE' };
var SEEDED = {
  E: { plate: '102 TU 2002', vin: FIXTURES.B.vin, make: 'RENAULT', model: 'CLIO', year: 2017, note: 'existing vehicle = card B' },
  F: { plate: '103 TU 2003', vin: null, make: 'VOLKSWAGEN', model: 'POLO', year: 2016, note: 'carries card C\'s plate, no VIN' },
  G: { plate: '104 TU 2004', vin: FIXTURES.C.vin, make: 'VOLKSWAGEN', model: 'GOLF', year: 2015, note: 'carries card C\'s VIN, another plate' }
};

function password() {
  // 20 characters, letters and digits (ops/auth-users.js rules: ≥ 12, letters + digits).
  var A = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789', s = '';
  while (!/[A-Za-z]/.test(s) || !/[0-9]/.test(s) || s.length < 20) { s = ''; for (var i = 0; i < 20; i++) s += A[crypto.randomInt(A.length)]; }
  return s;
}

async function main() {
  if (process.env.IDAUTO_STAGING !== '1') throw new Error('refusing: IDAUTO_STAGING=1 is not set');
  if (!/^idauto_scratch_cg2_/.test(process.env.IDAUTO_DB_NAME || '')) throw new Error('refusing: not the staging database');
  var accountsFile = process.env.IDAUTO_STAGING_ACCOUNTS;
  if (!accountsFile) throw new Error('IDAUTO_STAGING_ACCOUNTS is not set');
  var db = require(path.join(__dirname, '..', 'reference', 'db.js'));
  var dbName = (await db.query('SELECT current_database() d')).rows[0].d;
  if (!/^idauto_scratch_cg2_/.test(dbName)) throw new Error('refusing: connected to ' + dbName);
  if ((await db.query('SELECT count(*)::int n FROM idauto_auth_user')).rows[0].n) throw new Error('refusing: the database already has users — run reset, not seed');

  var orgA = (await db.query("INSERT INTO idauto_organizations (name, org_type, status) VALUES ('Atelier Démo Staging','garage','active') RETURNING id")).rows[0].id;
  var orgB = (await db.query("INSERT INTO idauto_organizations (name, org_type, status) VALUES ('Autre Atelier Staging','garage','active') RETURNING id")).rows[0].id;

  var auth = require(path.join(__dirname, '..', 'reference', 'auth', 'auth.js')).getAuth();
  var people = [
    { email: 'admin@staging.idauto.test', name: 'Admin Staging', role: 'admin', org: null },
    { email: 'atelier@staging.idauto.test', name: 'Gérant Atelier Démo', role: 'manager', org: orgA },
    { email: 'technicien@staging.idauto.test', name: 'Technicien Atelier Démo', role: 'technician', org: orgA },
    { email: 'autre-atelier@staging.idauto.test', name: 'Gérant Autre Atelier', role: 'manager', org: orgB }
  ];
  var lines = ['# IDauto CG2 STAGING — test accounts (synthetic). Generated ' + new Date().toISOString(),
    '# Keep this file private (mode 0600). Regenerated by `ops/staging-cg2.sh reset`.', ''];
  for (var i = 0; i < people.length; i++) {
    var p = people[i], pw = password();
    var u = await auth.api.signUpEmail({ body: { email: p.email, password: pw, name: p.name } });
    await db.query('UPDATE idauto_auth_user SET "role" = $1, "org_id" = $2 WHERE "id" = $3', [p.role, p.org, u.user.id]);
    lines.push(p.role.padEnd(11) + ' ' + p.email.padEnd(36) + ' ' + pw + (p.org ? '   (' + (p.org === orgA ? 'Atelier Démo Staging' : 'Autre Atelier Staging') + ')' : ''));
  }
  fs.writeFileSync(accountsFile, lines.join('\n') + '\n', { mode: 0o600 });
  fs.chmodSync(accountsFile, 0o600);

  var repo = require(path.join(__dirname, '..', 'reference', 'vehicle', 'vehicle-repository.js'));
  var plates = require(path.join(__dirname, '..', 'reference', 'vehicle', 'plate-normalizer.js'));
  var actor = { principal: { kind: 'admin', scopes: ['*'] }, identity: 'staging-seed' };
  var made = {};
  for (var k of Object.keys(SEEDED)) {
    var v = SEEDED[k];
    var row = await repo.createIdentifiedVehicle({ plate: plates.parsePlate(v.plate), vin: v.vin, make: v.make, model: v.model, year: v.year }, actor,
      { method: 'admin', source: 'staging_seed', confidence: 1 }, true);
    made[k] = row.ivid;
  }
  await db.closePool();
  console.log('seeded: 2 workshops, ' + people.length + ' accounts (passwords in ' + accountsFile + '), vehicles ' + Object.keys(made).map(function (k) { return k + '=' + made[k]; }).join(' '));
}

module.exports = { FIXTURES: FIXTURES, HOLDER: HOLDER, SEEDED: SEEDED };
if (require.main === module) main().catch(function (e) { console.error('seed failed: ' + e.message); process.exit(1); });
