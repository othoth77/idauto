#!/usr/bin/env python3
"""IDauto — IDA-UI-2 — builds reference/i18n-catalog-ar.js from the JSON sources in ops/ui/i18n/.

  strings-*.json   {"French text": "Arabic text"} — one file per area, merged in name order
  templates.json   [["French with {0}", "Arabic with {0}"], ...] — sentences that carry a value
A key already present keeps its first translation; identical French→French entries are dropped
(an untranslated key would only hide a missing translation). Run: python3 ops/ui/i18n/build-catalog.py
"""
import json, glob, os, re
D = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(D, '..', '..', '..', 'reference', 'i18n-catalog-ar.js')
strings = {}
for f in sorted(glob.glob(os.path.join(D, 'strings-*.json'))):
    for k, v in json.load(open(f, encoding='utf-8')).items():
        k = re.sub(r'\s+', ' ', k).strip()
        if k == '$comment' or not k or not v or v == k or k in strings: continue
        strings[k] = v.strip()
templates = json.load(open(os.path.join(D, 'templates.json'), encoding='utf-8'))
body = ('/* IDauto — IDA-UI-2 — the Arabic catalogue: French source text → Arabic.\n'
        ' * GENERATED by ops/ui/i18n/build-catalog.py from ops/ui/i18n/*.json — edit those, not this file.\n'
        ' * Templates carry {0}, {1}… for values. Test: tests/ida-ui-i18n-test.js. */\n'
        '(function (root) {\n  var C = ' + json.dumps({'strings': dict(sorted(strings.items())), 'templates': templates}, ensure_ascii=False, indent=1) + ';\n'
        "  if (typeof module !== 'undefined' && module.exports) module.exports = C; else root.IdAutoCatalogAr = C;\n"
        "}(typeof self !== 'undefined' ? self : this));\n")
open(OUT, 'w', encoding='utf-8').write(body)
print('strings', len(strings), 'templates', len(templates))
